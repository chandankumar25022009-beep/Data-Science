
# A3: Types of Data — Coding Practice

# 1. Numerical Data
age = 20
salary = 25000
height = 5.8

print("Age:", age)
print("Salary:", salary)
print("Height:", height)

# 2. Categorical Data
city = "Meerut"
color = "Blue"
education = "Diploma"

print("\nCity:", city)
print("Color:", color)
print("Education:", education)

# 3. Discrete and Continuous Data
number_of_students = 45  # Discrete: countable
temperature = 36.5       # Continuous: measurable

print("\nNumber of students:", number_of_students)
print("Temperature:", temperature)

# 4. Check Python Data Types
print("\nData types:")
print(type(age))
print(type(salary))
print(type(height))
print(type(city))
print(type(number_of_students))